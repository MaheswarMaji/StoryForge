def wrap(text, font, max_w):
    lines = []
    for para in text.strip().split("\n"):
        if not para.strip():
            lines.append("")
            continue
        cur = ""
        for word in para.split():
            trial = (cur + " " + word).strip()
            if font.getlength(trial) <= max_w or not cur:
                cur = trial
            else:
                lines.append(cur)
                cur = word
        lines.append(cur)
    return lines


def make_pdf(title, pages, title_font, body_font, out_path):
    page_imgs = []
    for i, (head, body) in enumerate(pages):
        img = Image.new("RGB", (W, H), (243, 236, 219))
        d = ImageDraw.Draw(img)
        for yy in range(0, H, 3):  # faint paper texture lines
            d.line([(0, yy), (W, yy)], fill=(241, 233, 214))
        tf = ImageFont.truetype(title_font, 52)
        bf = ImageFont.truetype(body_font, 40)
        d.text((W // 2, 110), title, font=tf, fill=(70, 40, 20), anchor="ma")
        d.line([(120, 210), (W - 120, 210)], fill=(160, 120, 70), width=3)
        y = 280
        for ln in wrap(body, bf, W - 280):
            d.text((140, y), ln, font=bf, fill=(40, 28, 18), anchor="la")
            y += int(40 * 1.75)
            if y > H - 160:
                break
        d.text((W // 2, H - 80), str(i + 1), font=ImageFont.truetype(title_font, 30),
               fill=(150, 110, 70), anchor="mm")
        d.text((W // 2, 40), "— ପୁରାତନ ପୁସ୍ତକ —" if False else ("पुरातन पुस्तक" if i % 2 else "पुरातन पुस्तक"), font=ImageFont.truetype(body_font, 26), fill=(170, 130, 80), anchor="mm")
        page_imgs.append(img)
    page_imgs[0].save(out_path, save_all=True, append_images=page_imgs[1:], resolution=150)
    print(f"wrote {out_path}")


